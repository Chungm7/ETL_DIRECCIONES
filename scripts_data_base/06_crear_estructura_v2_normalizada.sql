COMMENT ON COLUMN tb_tipo_zona.tizo_estado IS 'Estado del registro: A = Activo (tipo de habilitación urbana oficial vigente y aplicable), I = Inactivo (tipo deshabilitado o en desuso).';

-- -----------------------------------------------------------------------------
